"""In-process read-only vision adapter for an already finalized native RDP channel.

The channel independently authenticates the server, approved owner and NLA.
This module NEVER enrolls nodes, delegates credentials, creates Web/LLM
endpoints, or authorizes remote keyboard/mouse actions. It delivers only
complete decoded RGB frames as bounded PNGs to an explicitly trusted caller.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
from typing import Callable

from .rdp_bitmap_compositor import RDPComposedFrame
from .rdp_credssp_channel import PinnedRDPCredSSPChannel
from .rdp_frame_codec import encode_frame_png
from .rdp_graphics_stream import GraphicsStreamPolicy, GraphicsStreamResult

_MAX_PNG_BYTES = 36 * 1024 * 1024
_MAX_RGB_BYTES = 32 * 1024 * 1024


@dataclass(frozen=True)
class RDPVisionPNG:
    """Non-actionable, owner-scoped observation; never an input receipt."""

    width: int
    height: int
    png: bytes
    content_sha256: str
    update_count: int
    input_enabled: bool = False


@dataclass(frozen=True)
class RDPVisionResult:
    transport: GraphicsStreamResult
    png_delivered: int
    unchanged_frames_skipped: int
    desktop_verified: bool = False
    input_enabled: bool = False


def stream_native_rdp_png(
    channel: PinnedRDPCredSSPChannel,
    on_png: Callable[[RDPVisionPNG], None],
    *,
    reauthorize: Callable[[], None],
    policy: GraphicsStreamPolicy | None = None,
    max_png_frames: int = 32,
) -> RDPVisionResult:
    """Send bounded in-memory images from the SAME pinned RDP TLS connection.

    Call only after owner-approved CredSSP, MCS, licensing, Confirm Active and
    finalization on this exact channel. Its stream_bitmap_frames method enforces
    that protocol state; the separate reauthorize callback must verify the
    provider-authenticated owner's live session/node/rdp capability and not
    derive authority from text generated by a model.

    The synchronous sink is trusted, owner-scoped and must be nonblocking.
    It receives no credentials, input receipts, or handle to the RDP socket.
    The bridge never stores screenshots or creates files/network endpoints.
    All exits close the sensitive channel; a stopped or failed stream is never
    automatically resumed or replayed.
    """
    if not isinstance(channel, PinnedRDPCredSSPChannel):
        raise TypeError("Expected an enrolled, pinned native RDP channel")
    try:
        if not callable(on_png) or not callable(reauthorize):
            raise TypeError("Trusted PNG sink and owner reauthorization are required")
        if policy is None:
            policy = GraphicsStreamPolicy()
        if not isinstance(policy, GraphicsStreamPolicy):
            raise TypeError("Invalid native RDP stream policy")
        if type(max_png_frames) is not int or not 1 <= max_png_frames <= 256:
            raise ValueError("Invalid PNG frame delivery limit")

        last_digest: str | None = None
        last_update = 0
        delivered = 0
        unchanged = 0

        def forward(frame: RDPComposedFrame) -> None:
            nonlocal last_digest, last_update, delivered, unchanged
            reauthorize()
            if (type(frame) is not RDPComposedFrame
                    or frame.full_coverage is not True
                    or frame.input_enabled is not False
                    or type(frame.width) is not int
                    or type(frame.height) is not int
                    or type(frame.update_count) is not int
                    or not 1 <= frame.width <= 8192
                    or not 1 <= frame.height <= 8192
                    or frame.update_count <= last_update
                    or type(frame.rgb) is not bytes
                    or len(frame.rgb) != frame.width * frame.height * 3
                    or len(frame.rgb) > _MAX_RGB_BYTES):
                raise ValueError("Invalid or non-decoded RDP framebuffer")
            # The pixel digest is for duplicate suppression only, not proof of
            # owner approval, nor a token that could ever authorize input.
            digest = hashlib.sha256(
                frame.width.to_bytes(4, "big") +
                frame.height.to_bytes(4, "big") + frame.rgb
            ).hexdigest()
            if digest == last_digest:
                unchanged += 1
                last_update = frame.update_count
                return
            png = encode_frame_png(frame.width, frame.height, frame.rgb, mode="RGB")
            if not isinstance(png, bytes) or len(png) > _MAX_PNG_BYTES:
                raise ValueError("Encoded RDP PNG exceeds memory policy")
            # Encoding and hashing may be expensive; revocation after either
            # must prevent the image from reaching the trusted sink.
            reauthorize()
            observation = RDPVisionPNG(
                frame.width, frame.height, png, digest, frame.update_count
            )
            on_png(observation)
            last_digest = digest
            last_update = frame.update_count
            delivered += 1
            if delivered >= max_png_frames:
                channel.stop_graphics_stream()

        reauthorize()
        transport = channel.stream_bitmap_frames(forward, policy=policy)
        return RDPVisionResult(transport, delivered, unchanged)
    finally:
        channel.close()


__all__ = ["RDPVisionPNG", "RDPVisionResult", "stream_native_rdp_png"]
