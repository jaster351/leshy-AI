"""Read-only public Constitution routing for every Leshy chat interface.

Constitution is a shared project document, never a personal rule or a live web
fact. The answer is read from a real local file, not generated by the LLM.
"""
from __future__ import annotations

from hashlib import sha256
from datetime import datetime
from pathlib import Path
import re
import time
from typing import Any, Iterator

from .diagnostics import event, problem
from .realtime_chat import RealtimeChatManager, StreamEvent
from .storage import utcnow

RELATIVE_PATH = Path("constitution") / "CONSTITUTION_FEDERATION.md"
PUBLIC_PATH = "knowledge/constitution/CONSTITUTION_FEDERATION.md"
_MAX_BYTES = 96 * 1024
_ARTICLE = re.compile(r"(?m)^### Статья\s+(\d+)\.\s+")
_NUMBER_REQUEST = re.compile(r"(?i)\b(?:стать[ьяиюе]|ст\.)\s*(?:№\s*)?(\d{1,2})\b")


def is_federation_constitution_question(message: str) -> bool:
    """Do not intercept questions about the Constitution of the Russian Federation."""
    current = " ".join(str(message or "").lower().replace("ё", "е").split())
    law = "конституц" in current or "основной закон" in current
    leshy = bool(re.search(r"\bлеш\w*\b", current))
    federation = bool(re.search(r"\bфедерац\w*\b", current))
    local_possession = bool(re.search(
        r"\b(?:моя|наша|твоя|твою|твоей|ваша|вашу)\b.{0,50}\bконституц\w*|"
        r"\bконституц\w*\b.{0,50}\b(?:тебя|вас|лешего|леших)\b",
        current,
    ))
    russian = bool(re.search(r"\b(?:рф|росси\w*|российск\w*)\b", current))
    # "Леший, покажи Конституцию РФ" is NOT the federation document.
    return law and (leshy or federation or local_possession) and not russian


def _candidate_paths(app) -> list[Path]:
    roots: list[Path] = []
    worker = getattr(getattr(app, "self_learning", None), "repository_sync", None)
    directory = getattr(worker, "directory", None)
    if callable(directory):
        try:
            roots.append(Path(directory()))
        except (OSError, ValueError, TypeError):
            pass
    install_root = getattr(getattr(app, "settings", None), "install_root", None)
    if install_root is not None:
        roots.append(Path(install_root) / "knowledge")
    roots.append(Path(__file__).resolve().parents[2] / "knowledge")

    unique: list[Path] = []
    seen: set[str] = set()
    for root in roots:
        candidate = root / RELATIVE_PATH
        key = str(candidate)
        if key not in seen:
            seen.add(key)
            unique.append(candidate)
    return unique


def _verified_document(app) -> tuple[str, str, int, str] | None:
    for candidate in _candidate_paths(app):
        try:
            if candidate.is_symlink() or not candidate.is_file():
                continue
            stamp = candidate.stat()
            if not 0 < stamp.st_size <= _MAX_BYTES:
                continue
            raw = candidate.read_bytes()
            content = raw.decode("utf-8-sig").replace("\r\n", "\n")
            if not content.startswith("# Конституция Федерации Леших\n"):
                continue
            if not _ARTICLE.search(content):
                continue
            updated = datetime.fromtimestamp(stamp.st_mtime).astimezone().isoformat(timespec="seconds")
            return content, sha256(raw).hexdigest(), len(raw), updated
        except (OSError, UnicodeError, ValueError):
            continue
    return None


def constitution_answer(app, message: str) -> str | None:
    if not is_federation_constitution_question(message):
        return None
    verified = _verified_document(app)
    if verified is None:
        return (
            "Локальный текст Конституции Федерации Леших не найден или не прошёл "
            "проверку формата. Ожидаемый общий документ: " + PUBLIC_PATH +
            ". Я не проверял его через Интернет и не могу подтвердить "
            "сохранение в Knowledge на этом узле. Проверьте доставку обновления "
            "или синхронизацию общего каталога."
        )

    content, digest, size_bytes, file_mtime = verified
    count = len(_ARTICLE.findall(content))
    preface = (
        "Конституция Федерации Леших — общий документ проекта, а не пользовательское "
        "правило или Конституция РФ.\n"
        f"Источник на этом узле: {PUBLIC_PATH}\n"
        f"Статей: {count}. Размер файла: {size_bytes} байт.\n"
        f"Последнее изменение локальной копии: {file_mtime}.\n"
        f"SHA-256 фактических байтов локального файла: {digest}\n"
        "Текст прочитан из файла локального Knowledge, интернет-поиск не выполнялся."
    )
    number = _NUMBER_REQUEST.search(str(message or ""))
    if number:
        article = int(number.group(1))
        found = re.search(
            rf"(?ms)^### Статья {article}\.\s.*?(?=^### Статья \d+\.|^## |\Z)",
            content,
        )
        if found:
            return preface + "\n\n" + found.group(0).rstrip()
        return preface + f"\n\nСтатья {article} в прочитанной редакции не найдена."

    lower = str(message or "").lower()
    full = any(marker in lower for marker in (
        "полный", "целиком", "весь текст", "всю конституц", "покажи текст",
        "открой", "прочитай", "все статьи", "текст конституц",
    ))
    if full:
        return preface + "\n\n" + content.rstrip()

    if "создател" in lower or "владельц" in lower or "хозяин" in lower:
        sections = []
        for article in (12, 13, 14, 18):
            found = re.search(
                rf"(?ms)^### Статья {article}\.\s.*?(?=^### Статья \d+\.|^## |\Z)",
                content,
            )
            if found:
                sections.append(found.group(0).rstrip())
        return preface + "\n\n" + "\n\n".join(sections)

    intro = content.split("## Глава I.", 1)[0].strip()
    return (
        preface + "\n\n" + intro +
        "\n\nЧтобы прочитать документ целиком, спросите: "
        "«Покажи полный текст Конституции Федерации Леших»."
    )



_SHORT_ACKNOWLEDGEMENT = re.compile(
    r"(?iu)^\\s*(?:молодец|молодчина|умница|отлично|"
    r"спасибо(?:\\s+большое)?|благодарю|супер|класс|хорошо|"
    r"понятно|ясно|ок(?:ей)?)[\\s.!?👍👏🙏]*$"
)


def constitution_acknowledgement(
    app, message: str, owner_id: str, session_id: str | None
) -> str | None:
    """A short compliment after the *verified* document needs no model call.

    Verify the last assistant response in this owner's exact session and
    its hash against the local Constitution. Never infer this from a user
    quote, arbitrary memory, or a global previous conversation.
    """
    if not session_id or not _SHORT_ACKNOWLEDGEMENT.fullmatch(str(message or "")):
        return None
    from .owner_identity_runtime import canonical_owner
    owner = canonical_owner(app, str(owner_id or "web:local").strip()[:200])
    try:
        with app.storage.connection() as conn:
            row = conn.execute(
                "SELECT m.role,m.content FROM messages m "
                "JOIN sessions s ON s.id=m.session_id "
                "WHERE m.session_id=? AND s.owner_id=? "
                "ORDER BY m.id DESC LIMIT 1",
                (session_id, owner),
            ).fetchone()
        if row is None or row["role"] != "assistant":
            return None
        last = str(row["content"] or "")
        if not last.startswith(
            "Конституция Федерации Леших — общий документ проекта"
        ) or f"Источник на этом узле: {PUBLIC_PATH}\\n" not in last:
            return None
        verified = _verified_document(app)
        if verified is None:
            return None
        digest = verified[1]
        if f"SHA-256 фактических байтов локального файла: {digest}\\n" not in last:
            return None
        return "Спасибо!"
    except (OSError, ValueError, TypeError, KeyError):
        return None


def install_constitution_routing(app_class) -> None:
    """Install after other runtime wrappers so no stale-cache/web guard runs first."""
    old_stream = RealtimeChatManager.stream
    if not getattr(old_stream, "_leshy_constitution_route", False):
        def stream(
            self: RealtimeChatManager,
            message: str,
            *,
            owner_id: str = "web:local",
            session_id: str | None = None,
            request_id: str | None = None,
        ) -> Iterator[StreamEvent]:
            acknowledgement = constitution_acknowledgement(
                self.app, message, owner_id, session_id,
            )
            if not is_federation_constitution_question(message) and acknowledgement is None:
                yield from old_stream(
                    self, message, owner_id=owner_id,
                    session_id=session_id, request_id=request_id,
                )
                return

            rid, cancel = self._register(request_id)
            sid = ""
            started = time.monotonic()
            from .owner_identity_runtime import canonical_owner
            owner_id = canonical_owner(self.app, str(owner_id or "web:local").strip()[:200])
            try:
                sid, _rows = self._save_user_and_history(str(message).strip(), owner_id, session_id)
                yield StreamEvent("start", {
                    "request_id": rid, "session_id": sid, "sources": [],
                    "constitution_local": True,
                })
                if cancel.is_set():
                    yield StreamEvent("done", {
                        "request_id": rid, "session_id": sid, "answer": "",
                        "sources": [], "stopped": True,
                    })
                    return
                answer = acknowledgement if acknowledgement is not None else constitution_answer(self.app, message)
                if answer is None:
                    raise RuntimeError("Constitution intent unexpectedly missing")
                for chunk in self._chunk_fallback(answer, 160):
                    if cancel.is_set():
                        break
                    yield StreamEvent("delta", {"text": chunk})
                stopped = cancel.is_set()
                created_at = (
                    utcnow() if stopped
                    else self.app._save_assistant(sid, answer)
                )
                event(
                    "constitution_local_answer",
                    found=answer.startswith("Конституция Федерации"),
                    owner_id=owner_id,
                    latency_ms=int((time.monotonic() - started) * 1000),
                )
                yield StreamEvent("done", {
                    "request_id": rid, "session_id": sid,
                    "answer": "" if stopped else answer,
                    "created_at": created_at, "sources": [],
                    "stopped": stopped, "constitution_local": True,
                })
            except Exception as exc:
                problem("constitution_local_read_failed", type(exc).__name__)
                yield StreamEvent("error", {
                    "request_id": rid, "session_id": sid,
                    "error": str(exc), "constitution_local": True,
                })
            finally:
                self._unregister(rid)

        stream._leshy_constitution_route = True
        RealtimeChatManager.stream = stream

    old_chat = app_class.chat
    if not getattr(old_chat, "_leshy_constitution_route", False):
        def chat(
            self,
            message: str,
            *,
            owner_id: str = "web:local",
            session_id: str | None = None,
            **kwargs: Any,
        ) -> dict[str, Any]:
            acknowledgement = constitution_acknowledgement(
                self, message, owner_id, session_id,
            )
            if not is_federation_constitution_question(message) and acknowledgement is None:
                return old_chat(
                    self, message, owner_id=owner_id,
                    session_id=session_id, **kwargs,
                )
            from .owner_identity_runtime import canonical_owner
            owner = canonical_owner(self, str(owner_id or "web:local").strip()[:200])
            message = str(message or "").strip()
            sid = self._ensure_session(owner, session_id)
            now = utcnow()
            with self.storage.connection() as conn:
                conn.execute(
                    "INSERT INTO messages(session_id,role,content,created_at) VALUES(?,?,?,?)",
                    (sid, "user", message, now),
                )
                count = int(conn.execute(
                    "SELECT COUNT(*) AS c FROM messages WHERE session_id=?",
                    (sid,),
                ).fetchone()["c"])
                if count == 1:
                    conn.execute(
                        "UPDATE sessions SET title=?,title_source=?,updated_at=? WHERE id=?",
                        (" ".join(message.split())[:80], "auto", now, sid),
                    )
            answer = acknowledgement if acknowledgement is not None else constitution_answer(self, message)
            if answer is None:
                raise RuntimeError("Constitution intent unexpectedly missing")
            return {
                "session_id": sid,
                "answer": answer,
                "created_at": self._save_assistant(sid, answer),
                "sources": [], "constitution_local": True,
            }

        chat._leshy_constitution_route = True
        app_class.chat = chat


