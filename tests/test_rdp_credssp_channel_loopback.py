"""Loopback X.224 -> TLS -> multiple CredSSP packets on ONE real socket.

Only SPNEGO state is faked. A temporary X.509 cert is generated by OpenSSL,
which is a TEST dependency, not a requirement to run Leshy.
"""
from __future__ import annotations

import hashlib
import shutil
import socket
import ssl
import struct
import subprocess
import threading
import time

import pytest

import leshy.rdp_credssp_channel as chan
from leshy.rdp_credssp_tsrequest import TSRequest, decode_tsrequest, encode_tsrequest


class FakeSPNEGOFlow:
    def __init__(self, mechanism, cert, pin, *, authorize):
        authorize()
        self.server_bound = False
        self.turns = 0
        self.closed = False

    def start(self):
        return encode_tsrequest(TSRequest(nego_tokens=(b"client-gss",)))

    def receive(self, packet):
        self.turns += 1
        decoded = decode_tsrequest(packet)
        if self.turns == 1:
            assert decoded.nego_tokens == (b"server-gss",)
            return encode_tsrequest(TSRequest(
                pub_key_auth=b"sealed-binding", client_nonce=b"n" * 32
            ))
        assert self.turns == 2
        assert decoded.pub_key_auth == b"server-binding"
        self.server_bound = True
        return None

    def close(self):
        self.closed = True


@pytest.mark.parametrize("selected_protocol", [2, 8])
def test_real_loopback_tls_and_credssp_framing(tmp_path, monkeypatch, selected_protocol):
    openssl = shutil.which("openssl")
    if not openssl:
        pytest.skip("OpenSSL test utility not available")
    cert_file, key_file = tmp_path / "rdp.pem", tmp_path / "rdp.key"
    subprocess.run([
        openssl, "req", "-x509", "-newkey", "rsa:2048", "-nodes",
        "-sha256", "-days", "1", "-subj", "/CN=localhost",
        "-keyout", str(key_file), "-out", str(cert_file),
    ], check=True, capture_output=True, timeout=15)
    cert = ssl.PEM_cert_to_DER_cert(cert_file.read_text(encoding="ascii"))
    pin = hashlib.sha256(cert).hexdigest()
    listener = socket.create_server(("127.0.0.1", 0))
    listener.settimeout(10)
    port = listener.getsockname()[1]
    problems = []
    events = []

    def server():
        try:
            with listener:
                raw, _ = listener.accept()
                with raw:
                    raw.settimeout(10)
                    request = b""
                    while len(request) < 19:
                        packet = raw.recv(19 - len(request))
                        if not packet:
                            raise AssertionError("client closed during X.224")
                        request += packet
                    assert request[:4] == b"\x03\x00\x00\x13"
                    reply = (b"\x03\x00\x00\x13\x0e\xd0\x00\x00\x00\x00\x00"
                             + struct.pack("<BBHI", 2, 0, 8, selected_protocol))
                    raw.sendall(reply)
                    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
                    context.load_cert_chain(str(cert_file), str(key_file))
                    with context.wrap_socket(raw, server_side=True) as tls:
                        first = chan.read_tsrequest(tls, deadline=time.monotonic() + 8)
                        assert decode_tsrequest(first).nego_tokens == (b"client-gss",)
                        events.append("client-token")
                        tls.sendall(encode_tsrequest(
                            TSRequest(nego_tokens=(b"server-gss",))
                        ))
                        second = chan.read_tsrequest(tls, deadline=time.monotonic() + 8)
                        assert decode_tsrequest(second).pub_key_auth == b"sealed-binding"
                        events.append("client-binding")
                        tls.sendall(encode_tsrequest(
                            TSRequest(pub_key_auth=b"server-binding")
                        ))
        except BaseException as error:
            problems.append(error)

    worker = threading.Thread(target=server, daemon=True)
    worker.start()
    monkeypatch.setattr(chan, "CredSSPClient", FakeSPNEGOFlow)
    permissions = []
    with chan.connect_verified_rdp_credssp(
        "127.0.0.1", "rdp.example.org", pin,
        port=port, timeout=10,
        authorize=lambda ip, dns: permissions.append((ip, dns)),
    ) as client:
        assert client.credentials_delegated is False
        status = client.authenticate_server(mechanism_factory=lambda *a, **kw: object())
        assert status.server_bound
        assert status.rdp_desktop_available is False
        assert status.selected_protocol in ("CredSSP", "CredSSP-EX")
    worker.join(timeout=5)
    assert not worker.is_alive()
    assert not problems, [type(x).__name__ for x in problems]
    assert events == ["client-token", "client-binding"]
    assert all(x == ("127.0.0.1", "rdp.example.org") for x in permissions)
